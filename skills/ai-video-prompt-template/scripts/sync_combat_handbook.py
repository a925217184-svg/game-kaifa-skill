def adapt(text: str) -> str:
    for old, new in PATCHES:
        if old not in text:
            raise SystemExit("[FAIL] 适配补丁未命中（真源结构可能已变），中止：\n" + old[:80])
        text = text.replace(old, new)
    # 顶部插入适配说明（紧跟 H1 之后）
    lines = text.split("\n")
    assert lines[0].startswith("# "), lines[0]
    lines.insert(1, ADAPT_HEAD.strip("\n"))
    return "\n".join(lines)


def main():
    check = "--check" in sys.argv
    src = io.open(SRC, encoding="utf-8").read()
    adapted = adapt(src)

    import filecmp
    import shutil

    targets = [
        (DST_SEEDANCE, src, "seedance 技能（原样副本）", "byte"),
        (DST_AIVIDEO, adapted, "ai-video 技能（适配副本）", "text"),
    ]
    for path, content, label, mode in targets:
        d = os.path.dirname(path)
        if not os.path.isdir(d):
            print("[SKIP] 目录不存在：%s" % d)
            continue
        if check:
            if mode == "byte":
                ok = os.path.exists(path) and filecmp.cmp(SRC, path, shallow=False)
            else:
                ok = os.path.exists(path) and io.open(path, encoding="utf-8").read() == content
            print("[%s] %s -> %s" % ("OK  " if ok else "DIFF", label, path))
            continue
        if mode == "byte":
            # 按字节拷贝，保证与真源 md5 一致（不走文本重编码）
            shutil.copyfile(SRC, path)
            print("[WRITE] %s -> %s" % (label, path))
        else:
            io.open(path, "w", encoding="utf-8", newline="\n").write(content)
            print("[WRITE] %s -> %s (%d 字符)" % (label, path, len(content)))

    if not check:
        print("\n下一步（网页 AI 规范包）：")
        print("  python outputs/网页AI规范包/_source/build_pack.py")


if __name__ == "__main__":
    main()
